import {defineArrayMember, defineField, defineType} from 'sanity'
import {validateSlug} from '../../lib/slugValidation'

const availabilityOptions = [
  {title: 'Available now', value: 'available-now'},
  {title: 'Available to enquire', value: 'enquire'},
  {title: 'Seasonal', value: 'seasonal'},
  {title: 'Unavailable', value: 'unavailable'},
]

export const product = defineType({
  name: 'product',
  title: 'Product',
  type: 'document',
  groups: [
    {name: 'overview', title: 'Overview', default: true},
    {name: 'details', title: 'Product details'},
    {name: 'relationships', title: 'Related content'},
    {name: 'seo', title: 'Search and social'},
  ],
  fields: [
    defineField({
      name: 'name',
      title: 'Product name',
      type: 'string',
      group: 'overview',
      validation: (rule) => rule.required().min(2).max(100),
    }),
    defineField({
      name: 'slug',
      title: 'URL slug',
      type: 'slug',
      group: 'overview',
      description: 'Stable, lowercase URL used for this product.',
      options: {source: 'name', maxLength: 96},
      validation: (rule) => rule.required().custom(validateSlug),
    }),
    defineField({
      name: 'category',
      title: 'Category',
      type: 'reference',
      group: 'overview',
      description: 'Choose one catalogue category. Hydroponic is a growing method, not a category.',
      to: [{type: 'category'}],
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'shortDescription',
      title: 'Short description',
      type: 'text',
      rows: 3,
      group: 'overview',
      description: 'A factual summary for product cards and the top of the product page.',
      validation: (rule) => rule.required().min(20).max(180),
    }),
    defineField({
      name: 'description',
      title: 'Full description',
      type: 'blockContent',
      group: 'overview',
      description: 'Optional editorial detail. Do not include unsupported supply or growing claims.',
    }),
    defineField({
      name: 'images',
      title: 'Gallery',
      type: 'array',
      group: 'overview',
      description:
        'Optional during bulk text import. The first image is the main catalogue image once added. Drag to control gallery order. The public site shows a placeholder until at least one image exists.',
      of: [defineArrayMember({type: 'productImage'})],
      validation: (rule) => rule.max(10),
    }),
    defineField({
      name: 'availability',
      title: 'Availability',
      type: 'string',
      group: 'details',
      description: 'Editorial availability only; this is not live inventory.',
      options: {list: availabilityOptions, layout: 'radio'},
      initialValue: 'enquire',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'seasonal',
      title: 'Seasonal product',
      type: 'boolean',
      group: 'details',
      description: 'Enable when availability is tied to a season.',
      initialValue: false,
    }),
    defineField({
      name: 'growingMethod',
      title: 'Growing method',
      type: 'string',
      group: 'details',
      description: 'Use only when the method is verified. Hydroponic is managed here as an attribute.',
      options: {
        list: [
          {title: 'Hydroponic', value: 'hydroponic'},
          {title: 'Soil grown', value: 'soil-grown'},
          {title: 'Other verified method', value: 'other'},
        ],
      },
    }),
    defineField({
      name: 'badges',
      title: 'Badges',
      type: 'array',
      group: 'details',
      description: 'Select only labels that are current and supported.',
      of: [
        defineArrayMember({
          type: 'string',
          options: {
            list: [
              {title: 'Available Now', value: 'available-now'},
              {title: 'Seasonal', value: 'seasonal'},
              {title: 'Hydroponic', value: 'hydroponic'},
              {title: 'Chef Favourite', value: 'chef-favourite'},
              {title: 'New Arrival', value: 'new-arrival'},
            ],
          },
        }),
      ],
      options: {layout: 'tags'},
      validation: (rule) => rule.unique().max(5),
    }),
    defineField({
      name: 'suitableFor',
      title: 'Suitable for',
      type: 'array',
      group: 'details',
      description: 'Professional buyer or use contexts this product is suited to.',
      of: [
        defineArrayMember({
          type: 'string',
          options: {
            list: [
              {title: 'Restaurants and chefs', value: 'restaurants-chefs'},
              {title: 'Hotels and hospitality', value: 'hotels-hospitality'},
              {title: 'Retailers', value: 'retailers'},
              {title: 'Resellers and distributors', value: 'resellers-distributors'},
            ],
          },
        }),
      ],
      options: {layout: 'tags'},
      validation: (rule) => rule.unique(),
    }),
    defineField({
      name: 'packSizes',
      title: 'Pack sizes',
      type: 'array',
      group: 'details',
      description: 'Add only confirmed pack formats. Do not imply current stock.',
      of: [defineArrayMember({type: 'string', validation: (rule) => rule.max(80)})],
      validation: (rule) => rule.unique().max(12),
    }),
    defineField({
      name: 'culinaryUses',
      title: 'Culinary uses',
      type: 'array',
      group: 'details',
      description: 'Short, practical applications for professional kitchens.',
      of: [defineArrayMember({type: 'string', validation: (rule) => rule.max(100)})],
      validation: (rule) => rule.unique().max(12),
    }),
    defineField({
      name: 'storageAndHandling',
      title: 'Storage and handling',
      type: 'text',
      rows: 4,
      group: 'details',
      description: 'Optional verified handling guidance.',
      validation: (rule) => rule.max(600),
    }),
    defineField({
      name: 'relatedProducts',
      title: 'Related products',
      type: 'array',
      group: 'relationships',
      description: 'Curate genuinely relevant alternatives or complementary produce.',
      of: [defineArrayMember({type: 'reference', to: [{type: 'product'}]})],
      validation: (rule) => rule.unique().max(6),
    }),
    defineField({
      name: 'featured',
      title: 'Featured product',
      type: 'boolean',
      group: 'relationships',
      description: 'Makes the product eligible for featured-product placements.',
      initialValue: false,
    }),
    defineField({name: 'seo', title: 'Search and social', type: 'seo', group: 'seo'}),
  ],
  preview: {
    select: {
      title: 'name',
      category: 'category.title',
      availability: 'availability',
      media: 'images.0',
    },
    prepare: ({title, category, availability, media}) => ({
      title,
      subtitle: [category, availability].filter(Boolean).join(' · '),
      media,
    }),
  },
  orderings: [
    {title: 'Product name', name: 'nameAsc', by: [{field: 'name', direction: 'asc'}]},
    {title: 'Recently updated', name: 'updatedDesc', by: [{field: '_updatedAt', direction: 'desc'}]},
  ],
})
