import {defineArrayMember, defineField, defineType} from 'sanity'

export const homepage = defineType({
  name: 'homepage',
  title: 'Homepage',
  type: 'document',
  description: 'Homepage copy and curated merchandising. Maintain one document only.',
  groups: [
    {name: 'hero', title: 'Hero', default: true},
    {name: 'merchandising', title: 'Merchandising'},
    {name: 'seo', title: 'Search and social'},
  ],
  fields: [
    defineField({
      name: 'eyebrow',
      title: 'Hero eyebrow',
      type: 'string',
      group: 'hero',
      description: 'Optional short label above the main heading.',
      validation: (rule) => rule.max(50),
    }),
    defineField({
      name: 'heading',
      title: 'Hero heading',
      type: 'string',
      group: 'hero',
      description: 'State the offer clearly without unsupported claims.',
      validation: (rule) => rule.required().min(10).max(100),
    }),
    defineField({
      name: 'introduction',
      title: 'Hero introduction',
      type: 'text',
      rows: 3,
      group: 'hero',
      description: 'A concise B2B value proposition.',
      validation: (rule) => rule.required().min(30).max(240),
    }),
    defineField({
      name: 'heroImage',
      title: 'Hero image',
      type: 'image',
      group: 'hero',
      options: {hotspot: true},
      fields: [
        defineField({
          name: 'alt',
          title: 'Alternative text',
          type: 'string',
          validation: (rule) => rule.required().max(160),
        }),
      ],
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'featuredCategories',
      title: 'Featured categories',
      type: 'array',
      group: 'merchandising',
      description: 'Drag to set homepage order. Use category documents for category copy and imagery.',
      of: [defineArrayMember({type: 'reference', to: [{type: 'category'}]})],
      validation: (rule) => rule.unique().max(6),
    }),
    defineField({
      name: 'featuredProducts',
      title: 'Featured products',
      type: 'array',
      group: 'merchandising',
      description: 'Curated homepage products in display order.',
      of: [defineArrayMember({type: 'reference', to: [{type: 'product'}]})],
      validation: (rule) => rule.unique().max(8),
    }),
    defineField({
      name: 'seasonalProducts',
      title: 'Seasonal or timely products',
      type: 'array',
      group: 'merchandising',
      description:
        'Curated seasonal discovery; this does not represent live inventory. Keep product availability fields current.',
      of: [defineArrayMember({type: 'reference', to: [{type: 'product'}]})],
      validation: (rule) => rule.unique().max(8),
    }),
    defineField({
      name: 'featuredJournalEntries',
      title: 'Culinary inspiration',
      type: 'array',
      group: 'merchandising',
      description: 'Journal entries shown on the homepage in display order.',
      of: [defineArrayMember({type: 'reference', to: [{type: 'journalEntry'}]})],
      validation: (rule) => rule.unique().max(4),
    }),
    defineField({
      name: 'quoteCtaHeading',
      title: 'Quote call-to-action heading',
      type: 'string',
      group: 'merchandising',
      description: 'Closing prompt for professional buyers.',
      validation: (rule) => rule.max(100),
    }),
    defineField({
      name: 'quoteCtaText',
      title: 'Quote call-to-action text',
      type: 'text',
      rows: 2,
      group: 'merchandising',
      validation: (rule) => rule.max(220),
    }),
    defineField({name: 'seo', title: 'Search and social', type: 'seo', group: 'seo'}),
  ],
  preview: {
    select: {heading: 'heading', media: 'heroImage'},
    prepare: ({heading, media}) => ({title: 'Homepage', subtitle: heading, media}),
  },
})
